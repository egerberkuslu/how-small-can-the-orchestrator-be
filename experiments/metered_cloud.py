"""E9: metered-cloud regime — tests whether forward-looking DRL beats Greedy.

Real cloud offloading is not free: API calls and egress are billed, so a
deployment has a finite per-episode cloud budget. We cap the cloud to K uses
per episode (env cloud_budget=K); a cloud choice with no quota left falls back
to the cheaper of local/edge. The cloud is then a scarce resource that must be
rationed over the 200-task episode. A myopic policy spends the quota on the
first tasks where the cloud is cheapest and runs out before the tasks that need
it most; a forward-looking policy reserves the quota for high-value tasks (bad
channel, large transfer) where local/edge are far worse. This is an online
resource-allocation problem in which one-step-greedy is provably suboptimal,
so it is exactly where a learned policy should pull ahead.

Trains DQN[64,64] on the metered env (7-dim obs incl. quota left) and evaluates
DQN, Greedy, and the fixed heuristics. Idempotent; models in results/models/metered/.
"""

from __future__ import annotations

import os

os.environ.setdefault("OMP_NUM_THREADS", "1")
import numpy as np
import pandas as pd
import torch

torch.set_num_threads(1)

from stable_baselines3 import DQN
from stable_baselines3.common.monitor import Monitor

from env.offload_env import OffloadEnv
from agents.baselines import Greedy, AlwaysLocal, AlwaysEdge, RandomPolicy
from experiments.common import RESULTS, rollout_episode
from experiments.evaluate import PAPER_TBL

BUDGET = 40  # cloud calls per 200-task episode
STEPS = 300_000
SEEDS = 5
GAMMA = 0.997  # long horizon: rationing pays off ~tens of steps later
MODEL_DIR = os.path.join(RESULTS, "models", "metered")
os.makedirs(MODEL_DIR, exist_ok=True)


def train_seed(seed):
    path = os.path.join(MODEL_DIR, f"dqn_cb{BUDGET}_v2_s{seed}.zip")
    if os.path.exists(path):
        return path
    env = OffloadEnv(w1=0.5, cloud_budget=BUDGET)
    env.reset(seed=1234 + seed)
    env = Monitor(env, os.path.join(MODEL_DIR, f"mon_s{seed}"))
    model = DQN(
        "MlpPolicy",
        env,
        learning_rate=1e-4,
        buffer_size=100_000,
        batch_size=64,
        gamma=GAMMA,
        train_freq=4,
        target_update_interval=1000,
        exploration_fraction=0.2,
        exploration_final_eps=0.05,
        policy_kwargs=dict(net_arch=[64, 64]),
        device="cpu",
        seed=seed,
        verbose=0,
    )
    model.learn(total_timesteps=STEPS, progress_bar=False)
    model.save(path)
    return path


class _Wrap:
    def __init__(self, m):
        self.m = m

    def predict(self, obs, deterministic=True):
        a, _ = self.m.predict(obs, deterministic=deterministic)
        return int(a), None


def eval_pol(make_pol, n=100):
    cs = []
    for i in range(n):
        e = OffloadEnv(w1=0.5, cloud_budget=BUDGET)
        e.reset(seed=1000 + i)
        cs.append(rollout_episode(e, make_pol(e))["cost"])
    return np.mean(cs), np.std(cs, ddof=1)


def main():
    print(
        f"[E9] training DQN, metered cloud budget={BUDGET}, {SEEDS} seeds", flush=True
    )
    paths = [train_seed(s) for s in range(SEEDS)]
    rows = []
    per_seed = []
    for p in paths:
        m = DQN.load(p, device="cpu")
        cs = []
        for i in range(100):
            e = OffloadEnv(w1=0.5, cloud_budget=BUDGET)
            e.reset(seed=1000 + i)
            cs.append(rollout_episode(e, _Wrap(m))["cost"])
        per_seed.append(float(np.mean(cs)))
    rows.append(
        {
            "method": "DQN[64,64]",
            "cost_mean": float(np.mean(per_seed)),
            "cost_std": float(np.std(per_seed, ddof=1)),
        }
    )
    for name, mk in [
        ("Greedy", lambda e: Greedy(e)),
        ("AlwaysLocal", lambda e: AlwaysLocal(e)),
        ("AlwaysEdge", lambda e: AlwaysEdge(e)),
        ("Random", lambda e: RandomPolicy(e)),
    ]:
        mu, sd = eval_pol(mk)
        rows.append({"method": name, "cost_mean": mu, "cost_std": sd})

    df = pd.DataFrame(rows)
    df.to_csv(os.path.join(RESULTS, "e9_metered_cloud.csv"), index=False)
    write_t7(df)
    print(df.to_string(index=False), flush=True)
    d = df[df.method == "DQN[64,64]"]["cost_mean"].iloc[0]
    g = df[df.method == "Greedy"]["cost_mean"].iloc[0]
    print(
        f"[E9] DQN {d:.3f} vs Greedy {g:.3f} -> "
        f"{'DRL WINS' if d < g else 'Greedy still ahead'} ({100*(g-d)/g:+.1f}%)",
        flush=True,
    )


def write_t7(df):
    best = df["cost_mean"].min()
    lines = [
        "% Auto-generated by experiments/metered_cloud.py",
        "\\begin{table}[!t]\\centering\\footnotesize\\setlength{\\tabcolsep}{5pt}",
        "\\caption{Metered-cloud regime (40 cloud calls per episode). The "
        "learned policy rations the scarce cloud but does not beat myopic Greedy. "
        "Best in bold.}",
        "\\label{tab:metered}",
        "\\begin{tabular}{l c}",
        "\\toprule",
        "Method & Weighted cost \\\\",
        "\\midrule",
    ]
    for _, r in df.iterrows():
        c = f"{r['cost_mean']:.3f}{{\\scriptstyle\\pm{r['cost_std']:.3f}}}"
        if abs(r["cost_mean"] - best) < 1e-9:
            c = f"\\mathbf{{{r['cost_mean']:.3f}}}{{\\scriptstyle\\pm{r['cost_std']:.3f}}}"
        lines.append(f"{r['method']} & ${c}$ \\\\")
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}", ""]
    open(os.path.join(PAPER_TBL, "T7_metered.tex"), "w").write("\n".join(lines))


if __name__ == "__main__":
    main()
