"""Build paper/tables/T4_llm.tex from results/e5_llm_*.csv."""

from __future__ import annotations

import os
import pandas as pd

from experiments.common import RESULTS
from experiments.evaluate import PAPER_TBL

LLM_SIZE_GB = 4.9  # llama3.1:8b q4_K_M on-disk
LLM_PARAMS = "8B"


def main():
    sp = os.path.join(RESULTS, "e5_llm_summary.csv")
    ep = os.path.join(RESULTS, "e5_llm_episodes.csv")
    if not (os.path.exists(sp) and os.path.exists(ep)):
        print("E5 results missing; skip T4")
        return
    s = pd.read_csv(sp)
    e = pd.read_csv(ep)
    # optional chain-of-thought variant (E10)
    cot_sp = os.path.join(RESULTS, "e10_cot_summary.csv")
    cot_ep = os.path.join(RESULTS, "e10_cot_episodes.csv")
    has_cot = os.path.exists(cot_sp) and os.path.exists(cot_ep)
    lines = [
        "% Auto-generated by experiments/make_t4.py",
        "\\begin{table}[!t]\\centering\\footnotesize\\setlength{\\tabcolsep}{4pt}",
        "\\caption{Zero-shot LLM agent (llama3.1:8b, $\\sim$4.9~GB); Greedy "
        "reference on the same episodes.}",
        "\\label{tab:llm}",
        "\\begin{tabular}{l c c c c}",
        "\\toprule",
        "Variant & Cost & s/dec & Parse\\% & Agree\\% \\\\",
        "\\midrule",
    ]
    gref = e[e["variant"] == "Greedy-ref"]
    gcost = float(gref["cost"].mean()) if len(gref) else float("nan")
    name = {"P1": "LLM (P1)", "P2": "LLM (P2)"}
    for _, r in s.iterrows():
        v = r["variant"]
        cost = float(e[e["variant"] == v]["cost"].mean())
        parse_ok = 100.0 - float(r["parse_failure_pct"])
        lines.append(
            f"{name.get(v, 'LLM ('+v+')')} & {cost:.3f} & "
            f"{r['decision_latency_s_mean']:.2f} & {parse_ok:.1f} & "
            f"{r['agreement_greedy_pct']:.1f} \\\\"
        )
    if has_cot:
        cs = pd.read_csv(cot_sp).iloc[0]
        cc = float(pd.read_csv(cot_ep)["cost"].mean())
        lines.append(
            f"LLM (P3, CoT) & {cc:.3f} & {cs['decision_latency_s_mean']:.2f} & "
            f"{100.0-float(cs['parse_failure_pct']):.1f} & "
            f"{cs['agreement_greedy_pct']:.1f} \\\\"
        )
    lines.append(
        f"\\midrule\nGreedy (ref) & {gcost:.3f} & " "$<10^{-3}$ & -- & -- \\\\"
    )
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}", ""]
    open(os.path.join(PAPER_TBL, "T4_llm.tex"), "w").write("\n".join(lines))
    print("wrote T4_llm.tex")


if __name__ == "__main__":
    main()
