"""E3: lightweight study — three DQN sizes + int8 dynamic quantization.

The three sizes come from E1 (results/e1_results.csv). We additionally apply
dynamic int8 quantization to DQN[256,256] (seed 0), then report size / latency /
cost deltas. Writes results/e3_lightweight.csv and paper/tables/T3_lightweight.tex.
"""

from __future__ import annotations

import copy
import os
import tempfile
import numpy as np
import pandas as pd
import torch

from stable_baselines3 import DQN

from env.offload_env import OffloadEnv
from experiments.common import (
    RESULTS,
    model_path,
    rollout_episode,
    aggregate,
    count_params,
    inference_latency_us,
)
from experiments.evaluate import EVAL_SEEDS, PAPER_TBL, _SB3Wrap


def eval_cost(make_policy):
    rows = []
    for es in EVAL_SEEDS:
        env = OffloadEnv(w1=0.5)
        env.reset(seed=int(es))
        rows.append(rollout_episode(env, make_policy(env)))
    return aggregate(rows)


def raw_qnet_latency(arch, seed=0):
    """Single-thread latency of the bare q-network forward pass (same
    measurement base as the int8 row, so T3 is apples-to-apples)."""
    p = model_path("DQN", arch, 0.5, seed)
    model = DQN.load(p, device="cpu")
    qnet = model.policy.q_net.eval()

    def pf(obs):
        with torch.no_grad():
            t = torch.as_tensor(np.asarray(obs, dtype=np.float32)).reshape(1, 6)
            return int(qnet(t).argmax(dim=1).item())

    return round(inference_latency_us(pf, np.zeros(6, np.float32)), 2)


def quantize_dqn256():
    """Dynamic int8 quantization of the DQN[256,256] q-net (seed 0)."""
    p = model_path("DQN", "256x256", 0.5, 0)
    if not os.path.exists(p):
        return None
    model = DQN.load(p, device="cpu")
    qnet = copy.deepcopy(model.policy.q_net).eval()
    qnet_q = torch.ao.quantization.quantize_dynamic(
        qnet, {torch.nn.Linear}, dtype=torch.qint8
    )

    # size: serialize state_dict to a temp file
    def sd_size_kb(module):
        f = tempfile.NamedTemporaryFile(delete=False, suffix=".pt")
        torch.save(module.state_dict(), f.name)
        kb = os.path.getsize(f.name) / 1024.0
        os.unlink(f.name)
        return kb

    size_fp = sd_size_kb(qnet)
    size_q = sd_size_kb(qnet_q)

    obs_dim = 6

    def make_predict(net):
        def pf(obs):
            with torch.no_grad():
                t = torch.as_tensor(np.asarray(obs, dtype=np.float32)).reshape(
                    1, obs_dim
                )
                q = net(t)
                return int(q.argmax(dim=1).item()), None

        return pf

    us_q = inference_latency_us(make_predict(qnet_q), np.zeros(obs_dim, np.float32))
    us_fp = inference_latency_us(make_predict(qnet), np.zeros(obs_dim, np.float32))

    # cost of the quantized policy over the eval episodes
    class QWrap:
        def __init__(self, env):
            self.pf = make_predict(qnet_q)

        def predict(self, obs, deterministic=True):
            return self.pf(obs)

    agg = eval_cost(lambda env: QWrap(env))
    return {
        "params": count_params(qnet),
        "size_kb_fp32": round(size_fp, 1),
        "size_kb_int8": round(size_q, 1),
        "infer_us_fp32": round(us_fp, 2),
        "infer_us_int8": round(us_q, 2),
        "cost_mean": agg["cost_mean"],
        "cost_std": agg["cost_std"],
    }


def main():
    e1 = pd.read_csv(os.path.join(RESULTS, "e1_results.csv"))
    rows = []
    for arch in ["256x256", "64x64", "16x16"]:
        m = e1[e1["method"] == f"DQN[{arch}]"]
        if len(m) == 0:
            continue
        r = m.iloc[0]
        rows.append(
            {
                "variant": f"DQN[{arch}]",
                "params": int(r["params"]),
                "size_kb": float(r["size_kb"]),
                "infer_us": raw_qnet_latency(arch),
                "cost_mean": float(r["cost_mean"]),
                "cost_std": float(r["cost_std"]),
            }
        )

    q = quantize_dqn256()
    if q is not None:
        rows.append(
            {
                "variant": "DQN[256x256] int8",
                "params": q["params"],
                "size_kb": q["size_kb_int8"],
                "infer_us": q["infer_us_int8"],
                "cost_mean": q["cost_mean"],
                "cost_std": q["cost_std"],
            }
        )
        # also store the explicit fp32->int8 deltas for the paper text
        pd.DataFrame([q]).to_csv(
            os.path.join(RESULTS, "e3_quant_detail.csv"), index=False
        )

    df = pd.DataFrame(rows)
    df.to_csv(os.path.join(RESULTS, "e3_lightweight.csv"), index=False)
    _write_t3(df)
    print("wrote e3_lightweight.csv + T3_lightweight.tex", flush=True)
    print(df.to_string(index=False), flush=True)


def _write_t3(df):
    lines = [
        "% Auto-generated by experiments/lightweight.py",
        "\\begin{table}[!t]\\centering\\small",
        "\\caption{Lightweight study: parameter count, on-disk size, single-thread "
        "CPU inference latency of the bare q-network forward pass, and weighted "
        "cost for the three DQN sizes and the int8-quantized large policy.}",
        "\\label{tab:lightweight}",
        "\\begin{tabular}{l rrr r}",
        "\\toprule",
        "Variant & Params & Size (KB) & Infer ($\\mu$s) & Cost \\\\",
        "\\midrule",
    ]
    for _, r in df.iterrows():
        lines.append(
            f"{r['variant']} & {int(r['params'])} & {r['size_kb']:.1f} & "
            f"{r['infer_us']:.1f} & "
            f"${r['cost_mean']:.3f}{{\\scriptstyle\\pm{r['cost_std']:.3f}}}$ \\\\"
        )
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}", ""]
    open(os.path.join(PAPER_TBL, "T3_lightweight.tex"), "w").write("\n".join(lines))


if __name__ == "__main__":
    main()
