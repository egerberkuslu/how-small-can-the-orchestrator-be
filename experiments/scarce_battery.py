"""E7: scarce-battery regime — tests whether forward-looking control beats Greedy.

Motivation. On the nominal benchmark a myopic Greedy with full current-state
information is hard to beat, because the cloud is an unlimited fixed-cost escape
and there is little temporal coupling between decisions. We therefore add a
genuine sequential constraint that real battery-powered IoT devices face: a
tight energy budget. When the battery is small, every joule spent now is
unavailable later, and dropping below 20% capacity doubles the energy penalty
(env LOW_BATTERY_FRAC). A myopic policy spends energy whenever it is locally
cheapest and depletes the battery, running the tail of the episode in the
doubled-penalty regime; a learned policy can ration energy early to stay out of
that regime. This is the classic gap between one-step-greedy and long-horizon
control.

Trains DQN[64,64] in the scarce-battery regime over several seeds and evaluates
DQN, Greedy and the fixed heuristics on a shared bank of episodes. Idempotent:
trained models are cached under results/models/scarce/.
"""

from __future__ import annotations

import os

os.environ.setdefault("OMP_NUM_THREADS", "1")
import numpy as np
import pandas as pd
import torch

torch.set_num_threads(1)

from stable_baselines3 import DQN
from stable_baselines3.common.monitor import Monitor

from env.offload_env import OffloadEnv
from agents.baselines import Greedy, AlwaysLocal, AlwaysEdge, RandomPolicy
from experiments.common import RESULTS, rollout_episode
from experiments.evaluate import PAPER_TBL

BATT = 60.0  # J, tight battery (nominal is 1000 J)
STEPS = 250_000
SEEDS = 5
MODEL_DIR = os.path.join(RESULTS, "models", "scarce")
os.makedirs(MODEL_DIR, exist_ok=True)


def make_env(seed, monitor=None):
    e = OffloadEnv(w1=0.5, battery_capacity=BATT)
    e.reset(seed=seed)
    if monitor:
        e = Monitor(e, monitor)
    return e


def train_seed(seed):
    path = os.path.join(MODEL_DIR, f"dqn_batt{int(BATT)}_s{seed}.zip")
    if os.path.exists(path):
        return path
    env = make_env(1234 + seed, monitor=os.path.join(MODEL_DIR, f"mon_s{seed}"))
    model = DQN(
        "MlpPolicy",
        env,
        learning_rate=1e-4,
        buffer_size=100_000,
        batch_size=64,
        gamma=0.99,
        train_freq=4,
        target_update_interval=1000,
        exploration_fraction=0.2,
        exploration_final_eps=0.05,
        policy_kwargs=dict(net_arch=[64, 64]),
        device="cpu",
        seed=seed,
        verbose=0,
    )
    model.learn(total_timesteps=STEPS, progress_bar=False)
    model.save(path)
    return path


class _Wrap:
    def __init__(self, m):
        self.m = m

    def predict(self, obs, deterministic=True):
        a, _ = self.m.predict(obs, deterministic=deterministic)
        return int(a), None


def eval_policy(make_pol, n=100, seed0=1000, drl=False):
    cs, mr = [], []
    for i in range(n):
        e = OffloadEnv(w1=0.5, battery_capacity=BATT)
        e.reset(seed=seed0 + i)
        r = rollout_episode(e, make_pol(e))
        cs.append(r["cost"])
        mr.append(r["miss_rate"])
    return np.mean(cs), np.std(cs, ddof=1), np.mean(mr)


def main():
    print(f"[E7] training DQN at battery={BATT} J, {SEEDS} seeds", flush=True)
    paths = [train_seed(s) for s in range(SEEDS)]

    rows = []
    # DRL: mean across seeds, each evaluated on the same 100 episodes
    per_seed = []
    for p in paths:
        m = DQN.load(p, device="cpu")
        cs = []
        for i in range(100):
            e = OffloadEnv(w1=0.5, battery_capacity=BATT)
            e.reset(seed=1000 + i)
            cs.append(rollout_episode(e, _Wrap(m))["cost"])
        per_seed.append(float(np.mean(cs)))
    rows.append(
        {
            "method": "DQN[64,64]",
            "cost_mean": float(np.mean(per_seed)),
            "cost_std": float(np.std(per_seed, ddof=1)),
        }
    )
    for name, mk in [
        ("Greedy", lambda e: Greedy(e)),
        ("AlwaysLocal", lambda e: AlwaysLocal(e)),
        ("AlwaysEdge", lambda e: AlwaysEdge(e)),
        ("Random", lambda e: RandomPolicy(e)),
    ]:
        mu, sd, _ = eval_policy(mk)
        rows.append({"method": name, "cost_mean": mu, "cost_std": sd})

    df = pd.DataFrame(rows)
    df.to_csv(os.path.join(RESULTS, "e7_scarce_battery.csv"), index=False)
    write_t6(df)
    print(df.to_string(index=False), flush=True)
    g = df[df.method == "Greedy"]["cost_mean"].iloc[0]
    d = df[df.method == "DQN[64,64]"]["cost_mean"].iloc[0]
    print(
        f"[E7] DQN {d:.3f} vs Greedy {g:.3f} -> "
        f"{'DRL WINS' if d < g else 'Greedy still ahead'} "
        f"({100*(g-d)/g:+.1f}% vs Greedy)",
        flush=True,
    )


def write_t6(df):
    best = df["cost_mean"].min()
    lines = [
        "% Auto-generated by experiments/scarce_battery.py",
        "\\begin{table}[!t]\\centering\\footnotesize\\setlength{\\tabcolsep}{5pt}",
        "\\caption{Scarce-battery regime ($60$~J budget). The fixed heuristics "
        "collapse; the learned policy stays within noise of the strong Greedy "
        "baseline. Best in bold.}",
        "\\label{tab:scarce}",
        "\\begin{tabular}{l c}",
        "\\toprule",
        "Method & Weighted cost \\\\",
        "\\midrule",
    ]
    for _, r in df.iterrows():
        c = f"{r['cost_mean']:.3f}{{\\scriptstyle\\pm{r['cost_std']:.3f}}}"
        c = (
            f"\\mathbf{{{r['cost_mean']:.3f}}}{{\\scriptstyle\\pm{r['cost_std']:.3f}}}"
            if abs(r["cost_mean"] - best) < 1e-9
            else c
        )
        lines.append(f"{r['method']} & ${c}$ \\\\")
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}", ""]
    open(os.path.join(PAPER_TBL, "T6_scarce.tex"), "w").write("\n".join(lines))


if __name__ == "__main__":
    main()
